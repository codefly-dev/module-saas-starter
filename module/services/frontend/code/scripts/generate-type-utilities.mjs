#!/usr/bin/env node
// Compile the skin's type slots and control rungs into Tailwind utilities.
//
// The contract owns the vocabulary, the resolver flattens it onto `<html>` as
// custom properties, and this turns those properties into the class names
// components actually write: `type-card-title`, `control-sm`. Generated rather
// than hand-written so the stylesheet cannot drift from the contract — a slot
// added to the vocabulary and forgotten here would be a name that silently
// styles nothing.
//
//   node scripts/generate-type-utilities.mjs          # write
//   node scripts/generate-type-utilities.mjs --check   # fail if stale
//
// Every declaration reads a variable with no fallback, deliberately. All five
// typographic properties are INHERITED, so when a role does not decide one the
// variable is absent, the declaration is invalid at computed-value time, and the
// element inherits — exactly what the tree does today where a component sets no
// size or weight. A fallback would plant a value where none ever existed.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
	FRONTEND_CONTROL_SIZE_NAMES,
	FRONTEND_TYPE_SLOT_NAMES,
} from "@codefly/saas-plugin-contract";

const CODE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(CODE_ROOT, "src/app/type-slots.generated.css");

const HEADER = `/* Generated by scripts/generate-type-utilities.mjs — do not edit.
 *
 * One utility per type slot and per control rung, over the custom properties
 * src/lib/appearance.ts projects onto <html> from the resolved skin. A component
 * names its slot (\`type-card-title\`) or its rung (\`control-sm\`) and the skin
 * decides what that renders as.
 *
 * Each declaration reads its variable with no fallback on purpose: these are all
 * inherited properties, so a role that does not decide one leaves the variable
 * unset and the element inherits, which is what the untouched tree does today.
 */\n`;

const TYPE_PROPERTIES = [
	["font-size", "size"],
	["font-weight", "weight"],
	["line-height", "leading"],
	["letter-spacing", "tracking"],
	["font-family", "family"],
];

function typeUtility(name, prefix) {
	const body = TYPE_PROPERTIES.map(
		([property, suffix]) => `\t${property}: var(${prefix}-${suffix});`,
	).join("\n");
	return `@utility ${name} {\n${body}\n}\n`;
}

function render() {
	const blocks = [HEADER];
	for (const slot of FRONTEND_TYPE_SLOT_NAMES)
		blocks.push(typeUtility(`type-${slot}`, `--type-${slot}`));

	for (const size of FRONTEND_CONTROL_SIZE_NAMES) {
		// The whole rung: outer height, horizontal padding, and the type role the
		// rung carries. A caller choosing `size="sm"` chooses all of it.
		blocks.push(
			`@utility control-${size} {\n` +
				`\theight: var(--control-${size}-height);\n` +
				`\tpadding-inline: var(--control-${size}-padding-x);\n` +
				TYPE_PROPERTIES.map(
					([property, suffix]) =>
						`\t${property}: var(--control-${size}-text-${suffix});`,
				).join("\n") +
				`\n}\n`,
		);
		// Height alone, for a container that sizes to a rung without taking its
		// type (a tab list around its own triggers).
		blocks.push(
			`@utility control-height-${size} {\n\theight: var(--control-${size}-height);\n}\n`,
		);
		// A square control at the rung: width follows height, no inline padding.
		blocks.push(
			`@utility control-icon-${size} {\n` +
				`\theight: var(--control-${size}-height);\n` +
				`\twidth: var(--control-${size}-height);\n` +
				`\tpadding-inline: 0;\n` +
				TYPE_PROPERTIES.map(
					([property, suffix]) =>
						`\t${property}: var(--control-${size}-text-${suffix});`,
				).join("\n") +
				`\n}\n`,
		);
		// The rung's icon edge, for the glyphs inside a control.
		blocks.push(
			`@utility control-glyph-${size} {\n\twidth: var(--control-${size}-icon);\n\theight: var(--control-${size}-icon);\n}\n`,
		);
	}
	return blocks.join("\n");
}

const rendered = render();
if (process.argv.includes("--check")) {
	let current = "";
	try {
		current = readFileSync(OUTPUT, "utf8");
	} catch {
		console.error(
			`type utilities: ${OUTPUT} is missing — run node scripts/generate-type-utilities.mjs`,
		);
		process.exit(1);
	}
	if (current !== rendered) {
		console.error(
			`type utilities: ${OUTPUT} is stale — run node scripts/generate-type-utilities.mjs`,
		);
		process.exit(1);
	}
	console.log(
		`type utilities OK: ${FRONTEND_TYPE_SLOT_NAMES.length} slots, ${FRONTEND_CONTROL_SIZE_NAMES.length} control rungs`,
	);
} else {
	writeFileSync(OUTPUT, rendered);
	console.log(
		`type utilities written: ${FRONTEND_TYPE_SLOT_NAMES.length} slots, ${FRONTEND_CONTROL_SIZE_NAMES.length} control rungs`,
	);
}
