// Auto-discovers every AdminPlugin under src/plugins/ and writes a static
// registry barrel. A side-module (e.g. the warden console) registers simply by
// dropping a plugin file in src/plugins/ — zero edits to base files. Static
// output (no require.context / import.meta.glob) so it works identically under
// Next (webpack/turbopack) and the vitest (Vite) suite.
//
// Wired to predev/prebuild/pretest; coverage is enforced by
// src/plugins/__tests__/registry.test.ts.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pluginsDir = join(here, "..", "src", "plugins");
const GENERATED = "registry.generated.ts";

const files = readdirSync(pluginsDir, { withFileTypes: true })
  .filter((d) => d.isFile() && d.name.endsWith(".ts") && d.name !== GENERATED)
  .map((d) => d.name)
  .sort();

const imports = files
  .map((f, i) => `import * as p${i} from "./${f.replace(/\.ts$/, "")}";`)
  .join("\n");
const list = files.map((_, i) => `p${i}`).join(", ");

const out = `// CODE GENERATED by scripts/generate-plugin-registry.mjs — DO NOT EDIT.
//
// Every AdminPlugin under src/plugins/ is auto-discovered here, so adding a
// plugin file (e.g. a side-module's admin console) registers it with no edits
// to admin-config.ts or any other base file. Regenerated by predev/prebuild/
// pretest; coverage is enforced by __tests__/registry.test.ts.
import type { AdminPlugin } from "@/lib/admin-core";
${imports}

function pick(mod: Record<string, unknown>): AdminPlugin | undefined {
  return Object.values(mod).find(
    (v): v is AdminPlugin =>
      !!v && typeof v === "object" && typeof (v as { name?: unknown }).name === "string",
  );
}

export const discoveredPlugins: AdminPlugin[] = [${list}]
  .map(pick)
  .filter((p): p is AdminPlugin => p !== undefined);
`;

writeFileSync(join(pluginsDir, GENERATED), out);
console.log(`plugin registry: ${files.length} file(s) — ${files.join(", ")}`);
