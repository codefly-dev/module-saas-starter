// Auto-discovers every AdminPlugin and writes a static registry barrel. Two
// sources, in this order:
//
//   1. SHARED — every *.ts under src/plugins/ (the starter's OWN core plugins:
//      core-users, audit, platform-admin). Editing these is a change to the
//      starter "for itself" — it flows to every consumer.
//
//   2. PROJECT (opt-in) — a consumer (warden, mind, …) points the env var
//      SAAS_PROJECT_PLUGINS_DIR at ITS OWN plugins dir, which lives OUTSIDE this
//      (possibly symlinked) starter tree. Editing these is a change "for one
//      project" — it stays local and never touches the shared starter. We import
//      them by a RELATIVE path computed from the registry's location, so NO
//      bundler alias or tsconfig path is needed: relative imports resolve
//      identically under Next (webpack/turbopack) and the vitest (Vite) suite.
//      A project plugin's own `@/…` imports still resolve to the shared starter's
//      src (the `@` alias), so it reuses shared components while living apart.
//
// Unset SAAS_PROJECT_PLUGINS_DIR → byte-for-byte the old behavior (shared only).
//
// Wired to predev/prebuild/pretest; coverage is enforced by
// src/plugins/__tests__/registry.test.ts. Static output (no require.context /
// import.meta.glob) so Next and vitest agree.
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pluginsDir = join(here, "..", "src", "plugins");
const GENERATED = "registry.generated.ts";

const isPluginFile = (name) => name.endsWith(".ts") && name !== GENERATED;
const noExt = (name) => name.replace(/\.ts$/, "");

// 1. Shared plugins — imported relative to the registry (same dir).
const sharedSpecs = readdirSync(pluginsDir, { withFileTypes: true })
  .filter((d) => d.isFile() && isPluginFile(d.name))
  .map((d) => `./${noExt(d.name)}`)
  .sort();

// 2. Project plugins (opt-in) — imported by a relative path to the external dir.
// Discovery, in order: SAAS_PROJECT_PLUGINS_DIR (explicit override), else the
// CONVENTION `<app>/project-plugins/` (sibling to src/). The convention dir lives
// INSIDE the app code dir so the project plugins resolve the app's node_modules
// by the normal walk-up (react/next/@tanstack) with NO symlink, and it survives a
// starter re-sync because it's not part of the shared template (no prune). The
// canonical starter has no such dir, so it stays shared-only by default.
const projectDir = process.env.SAAS_PROJECT_PLUGINS_DIR || join(here, "..", "project-plugins");
let projectSpecs = [];
if (projectDir && existsSync(projectDir) && statSync(projectDir).isDirectory()) {
  projectSpecs = readdirSync(projectDir, { withFileTypes: true })
    .filter((d) => d.isFile() && isPluginFile(d.name))
    .map((d) => {
      // POSIX separators so the generated import is stable across platforms.
      let spec = relative(pluginsDir, join(projectDir, noExt(d.name))).replaceAll("\\", "/");
      if (!spec.startsWith(".")) spec = `./${spec}`;
      return spec;
    })
    .sort();
}

const specs = [...sharedSpecs, ...projectSpecs];
const imports = specs.map((s, i) => `import * as p${i} from "${s}";`).join("\n");
const list = specs.map((_, i) => `p${i}`).join(", ");

const out = `// CODE GENERATED by scripts/generate-plugin-registry.mjs — DO NOT EDIT.
//
// Discovered AdminPlugins: the starter's own under src/plugins/, plus any
// PROJECT plugins from SAAS_PROJECT_PLUGINS_DIR (a consumer's local dir outside
// this tree). Adding a plugin needs no edits here — regenerated by predev/
// prebuild/pretest; coverage enforced by __tests__/registry.test.ts.
import type { AdminPlugin } from "@/lib/admin-core";
${imports}

function pick(mod: Record<string, unknown>): AdminPlugin | undefined {
  return Object.values(mod).find(
    (v): v is AdminPlugin =>
      !!v && typeof v === "object" && typeof (v as { name?: unknown }).name === "string",
  );
}

export const discoveredPlugins: AdminPlugin[] = [${list}]
  .map(pick)
  .filter((p): p is AdminPlugin => p !== undefined);
`;

writeFileSync(join(pluginsDir, GENERATED), out);
console.log(
  `plugin registry: ${specs.length} plugin(s) — shared:[${sharedSpecs.join(", ")}]` +
    ` project:[${projectSpecs.join(", ") || "none"}]`,
);
