#!/usr/bin/env node
// Compile the kit, alone, into one plain stylesheet painted with the default
// skin: `@codefly-dev/ui/preview.css`.
//
// Every class a kit component writes is defined only where something compiled
// the kit's source with its token layer, and every variable those classes read
// is set only where a host projected a skin onto <html>. A solution authors no
// CSS, so without this it cannot render its own page anywhere but inside a
// running host. This is that compile, done once here, so a preview needs no
// Tailwind of its own.
//
//   node scripts/generate-preview-stylesheet.mjs          # write (from packages/codefly-ui)
//   node scripts/generate-preview-stylesheet.mjs --check   # fail if stale
//
// Reads the BUILT projection (`dist/skin/appearance.js`), so build the kit
// first; `prepare:frontend` does.
//
// Committed rather than built at publish: its bytes depend on more than this
// package — the contract's default skin and the Tailwind, Lightning CSS and
// tw-animate-css versions in the lockfile — and the kit-version gate judges only
// what is in this folder. A dist build could change under an unchanged version
// and be refused at publish as "already published with different contents".
// Committed, the bytes are what the gate diffs, and the --check here fails the
// moment any of those inputs moves without a regeneration.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { DEFAULT_FRONTEND_APPEARANCE } from "@codefly-dev/saas-plugin-contract";

import { appearanceStyleProperties } from "../dist/skin/appearance.js";

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SKIN = join(PACKAGE_ROOT, "src/skin");
// Overridable only so the host's test can prove `--check` refuses a stale copy
// without corrupting the tracked file other tests read.
const OUTPUT =
	process.env.PREVIEW_STYLESHEET_PATH ?? join(SKIN, "preview.generated.css");
const require = createRequire(join(PACKAGE_ROOT, "package.json"));
const postcss = require("postcss");
const tailwind = require("@tailwindcss/postcss");

const HEADER = `/* Generated by @codefly-dev/ui scripts/generate-preview-stylesheet.mjs — do not edit.
 *
 * The kit's components compiled with its token layer (theme.css) and type
 * utilities, painted with the DEFAULT skin. Import it once at the root of a
 * preview so kit components render without a running host.
 *
 * May be used for: a solution's local preview, its component stories, and the
 * screenshots or visual tests taken from them.
 *
 * May not be used for:
 * - Anything a host loads. A solution's remote renders inside the host's
 *   document under the host's one compiled stylesheet and the deployment's
 *   skin. Bundled into a remote, this ships a second Tailwind preflight and the
 *   default skin's values into that document.
 * - Evidence of how a deployment looks. It is the default skin; a deployment's
 *   skin changes colour, type, radius and density.
 * - Styling anything but kit components. Only classes the kit's own source
 *   writes are here, so a hand-laid utility in a solution renders unstyled in
 *   preview — the kit is what a solution page is built from.
 *
 * Dark mode: put class="dark" on an ancestor, as the host does.
 */
`;

// `source(none)`: only the kit's own source, never whatever happens to sit
// beside it, and never this output, which names every class it defines.
const ENTRY = `@import "tailwindcss" source(none);
@import "tw-animate-css";
@import "./theme.css";
@import "./type-slots.generated.css";
@source "../**/*.{ts,tsx}";
@source not "../**/__tests__";
`;

function defaults() {
	const properties = appearanceStyleProperties(DEFAULT_FRONTEND_APPEARANCE);
	const lines = Object.entries(properties)
		.map(([name, value]) => `\t${name}: ${value};`)
		.join("\n");
	// What the host writes as an inline style on <html>, here as the root rule.
	return `:root {\n${lines}\n}\n`;
}

async function render() {
	const result = await postcss([
		tailwind({ base: PACKAGE_ROOT, optimize: { minify: false } }),
	]).process(ENTRY + defaults(), {
		from: join(SKIN, "preview.entry.css"),
	});
	return `${HEADER}\n${result.css.trimEnd()}\n`;
}

const rendered = await render();
if (process.argv.includes("--check")) {
	if (readFileSync(OUTPUT, "utf8") !== rendered) {
		console.error(
			`preview stylesheet: ${OUTPUT} is stale — run node scripts/generate-preview-stylesheet.mjs`,
		);
		process.exit(1);
	}
	console.log("preview stylesheet OK");
} else {
	writeFileSync(OUTPUT, rendered);
	console.log(`preview stylesheet written: ${rendered.length} bytes`);
}
