#!/usr/bin/env node
// Compile the skin's type slots and control rungs into Tailwind utilities.
//
// The contract owns the vocabulary, the resolver flattens it onto `<html>` as
// custom properties, and this turns those properties into the class names
// components actually write: `type-card-title`, `control-sm`. Generated rather
// than hand-written so the stylesheet cannot drift from the contract — a slot
// added to the vocabulary and forgotten here would be a name that silently
// styles nothing.
//
//   node scripts/generate-type-utilities.mjs          # write (from packages/codefly-ui)
//   node scripts/generate-type-utilities.mjs --check   # fail if stale
//
// A utility declares ONLY the properties its slot's role decides. This is not
// an optimisation. An earlier version emitted all five properties and read an
// unset variable, on the reasoning that a declaration invalid at computed-value
// time "inherits, exactly like the untouched tree". That is false: such a
// declaration still WINS the cascade and only then computes to inherit, so it
// wipes any other class's value for that property on the same element. A
// caller's `font-mono tracking-[0.3em]` beside `md:type-input` lost both at the
// breakpoint, because the role behind `input` decides neither family nor
// tracking. Absence is the only thing that behaves like absence.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
	DEFAULT_FRONTEND_APPEARANCE,
	FRONTEND_CONTROL_SIZE_NAMES,
	FRONTEND_TYPE_SLOT_NAMES,
	resolveTypeRole,
	resolveTypeSlot,
} from "@codefly/saas-plugin-contract";

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// Ships with the package (`src` is in `files`) and is exported as
// `@codefly-dev/ui/type-slots.css`: the classes the kit's components name are
// defined by the kit, not by whichever consumer compiles them.
const OUTPUT = join(PACKAGE_ROOT, "src/skin/type-slots.generated.css");

const HEADER = `/* Generated by @codefly-dev/ui scripts/generate-type-utilities.mjs — do not edit.
 *
 * One Tailwind utility per type slot and per control rung, over the custom
 * properties the host projects onto <html> from the resolved skin
 * (\`--type-<slot>-size\`, \`--control-<size>-height\`, ...). A component names
 * its slot (\`type-card-title\`) or its rung (\`control-sm\`) and the skin decides
 * what that renders as. Import this file into the Tailwind entry that compiles
 * the kit's components; a remote renders inside the host's document, so the
 * variables are already there.
 *
 * Two rules make a slot compose with a raw utility on the same element the way
 * the tree composed before slots existed:
 *
 * 1. A utility declares only the properties its DEFAULT role decides. A
 *    declared property whose variable is unset does not vanish — it wins the
 *    cascade and then computes to inherit — so declaring a property the role
 *    leaves alone would wipe any other class's value for it.
 * 2. Every declaration sits under \`:where(&)\`, at zero specificity. A core
 *    utility (\`text-lg\`, \`h-11\`, \`size-8\`) on the same element therefore
 *    overrides that ONE property of the slot or rung whatever the source order,
 *    and the rest of the slot stands. tailwind-merge cannot express "override
 *    part of a class", so the kit's \`cn\` keeps both classes and lets the
 *    cascade do it. Two skin utilities on one element (a slot beside a rung)
 *    are both zero-specific and resolve by source order — the narrower one is
 *    emitted later, so a slot's text beats the text a rung carries.
 */
`;

// property → [custom-property suffix, key on the resolved slot]
const TYPE_PROPERTIES = [
	["font-size", "size", "fontSize"],
	["font-weight", "weight", "fontWeight"],
	["line-height", "leading", "lineHeight"],
	["letter-spacing", "tracking", "letterSpacing"],
	["font-family", "family", "fontFamily"],
];

/** The declarations for a resolved role: only what it decides. */
function typeDeclarations(prefix, resolved) {
	return TYPE_PROPERTIES.filter(([, , key]) => resolved[key] !== undefined).map(
		([property, suffix]) => `${property}: var(${prefix}-${suffix});`,
	);
}

/** One `@utility` whose declarations all sit at zero specificity. */
function utility(name, declarations) {
	if (declarations.length === 0)
		throw new Error(
			`${name} declares no property; a utility that declares nothing is a name that styles nothing`,
		);
	const body = declarations.map((line) => `\t\t${line}`).join("\n");
	return `@utility ${name} {\n\t:where(&) {\n${body}\n\t}\n}\n`;
}

function typeUtility(name, prefix, resolved) {
	return utility(name, typeDeclarations(prefix, resolved));
}

function render() {
	const blocks = [HEADER];
	const layers = DEFAULT_FRONTEND_APPEARANCE;
	for (const slot of FRONTEND_TYPE_SLOT_NAMES)
		blocks.push(
			typeUtility(
				`type-${slot}`,
				`--type-${slot}`,
				resolveTypeSlot(layers, slot),
			),
		);

	for (const size of FRONTEND_CONTROL_SIZE_NAMES) {
		const text = resolveTypeRole(layers, layers.controlSizes[size].text);
		// The whole rung: outer height, horizontal padding, and the type role the
		// rung carries. A caller choosing `size="sm"` chooses all of it.
		blocks.push(
			utility(`control-${size}`, [
				`height: var(--control-${size}-height);`,
				`padding-inline: var(--control-${size}-padding-x);`,
				...typeDeclarations(`--control-${size}-text`, text),
			]),
		);
		// Height alone, for a container that sizes to a rung without taking its
		// type (a tab list around its own triggers).
		blocks.push(
			utility(`control-height-${size}`, [
				`height: var(--control-${size}-height);`,
			]),
		);
		// A square control at the rung: width follows height, no inline padding.
		blocks.push(
			utility(`control-icon-${size}`, [
				`height: var(--control-${size}-height);`,
				`width: var(--control-${size}-height);`,
				`padding-inline: 0;`,
				...typeDeclarations(`--control-${size}-text`, text),
			]),
		);
		// The rung's icon edge, for the glyphs inside a control.
		blocks.push(
			utility(`control-glyph-${size}`, [
				`width: var(--control-${size}-icon);`,
				`height: var(--control-${size}-icon);`,
			]),
		);
	}
	return blocks.join("\n");
}

const rendered = render();
if (process.argv.includes("--check")) {
	let current = "";
	try {
		current = readFileSync(OUTPUT, "utf8");
	} catch {
		console.error(
			`type utilities: ${OUTPUT} is missing — run node scripts/generate-type-utilities.mjs`,
		);
		process.exit(1);
	}
	if (current !== rendered) {
		console.error(
			`type utilities: ${OUTPUT} is stale — run node scripts/generate-type-utilities.mjs`,
		);
		process.exit(1);
	}
	console.log(
		`type utilities OK: ${FRONTEND_TYPE_SLOT_NAMES.length} slots, ${FRONTEND_CONTROL_SIZE_NAMES.length} control rungs`,
	);
} else {
	writeFileSync(OUTPUT, rendered);
	console.log(
		`type utilities written: ${FRONTEND_TYPE_SLOT_NAMES.length} slots, ${FRONTEND_CONTROL_SIZE_NAMES.length} control rungs`,
	);
}
