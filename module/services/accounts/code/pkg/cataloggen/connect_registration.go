package cataloggen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strings"

	"google.golang.org/protobuf/encoding/protojson"
	"gopkg.in/yaml.v3"

	"accounts/pkg/business"
	catalogv1 "accounts/pkg/gen/saas/catalog/v1"
)

const connectBindingsVersion = "v1"

type connectBindings struct {
	Version  string                    `yaml:"version"`
	Services map[string]connectBinding `yaml:"services"`
}

type connectBinding struct {
	Handler    string               `yaml:"handler"`
	Source     connectBindingSource `yaml:"source"`
	GRPCServer string               `yaml:"grpc_server,omitempty"`
}

type connectBindingSource struct {
	Kind string `yaml:"kind"`
	Name string `yaml:"name,omitempty"`
}

// bindingFor resolves a service's binding: by full name first, so two services
// of one short name in different packages (the service's own InstallationService
// and an implemented interface's) bind apart; by short name otherwise, as every
// existing entry is spelled.
func bindingFor(bindings connectBindings, service *catalogv1.Service) (connectBinding, string, bool) {
	if binding, ok := bindings.Services[service.GetFullName()]; ok {
		return binding, service.GetFullName(), true
	}
	binding, ok := bindings.Services[service.GetName()]
	return binding, service.GetName(), ok
}

// generatedPackages names the Go packages protoc wrote for a service's protobuf
// package. The service's own API package keeps the historical aliases; an
// implemented interface's package gets aliases derived from its name, with the
// import paths buf's managed mode produces (accounts/pkg/gen + the package path).
type generatedPackages struct {
	genAlias, genPath, connectAlias, connectPath string
}

func generatedPackagesFor(catalog *catalogv1.ServiceCatalog, service *catalogv1.Service) generatedPackages {
	pkg := strings.TrimSuffix(service.GetFullName(), "."+service.GetName())
	if pkg == catalog.GetApiPackage() {
		return generatedPackages{genAlias: "gen", genPath: "accounts/pkg/gen/saas/accounts/v1", connectAlias: "genconnect", connectPath: "accounts/pkg/gen/saas/accounts/v1/accountsv1connect"}
	}
	parts := strings.Split(pkg, ".")
	alias := strings.Join(parts, "_")
	path := "accounts/pkg/gen/" + strings.Join(parts, "/")
	connectDir := strings.Join(parts[len(parts)-2:], "") + "connect"
	return generatedPackages{genAlias: alias, genPath: path, connectAlias: alias + "connect", connectPath: path + "/" + connectDir}
}

func importBlock(catalog *catalogv1.ServiceCatalog, bindings connectBindings, connect bool) string {
	seen := map[string]string{}
	for _, service := range catalog.GetServices() {
		pkgs := generatedPackagesFor(catalog, service)
		if connect {
			seen[pkgs.connectAlias] = pkgs.connectPath
			continue
		}
		// The raw-gRPC file registers only gRPC-backed services, so it imports
		// only their packages; an unused import would not compile.
		if binding, _, _ := bindingFor(bindings, service); grpcBacked(binding) {
			seen[pkgs.genAlias] = pkgs.genPath
		}
	}
	aliases := make([]string, 0, len(seen))
	for alias := range seen {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	var b strings.Builder
	for _, alias := range aliases {
		fmt.Fprintf(&b, "\t%s %q\n", alias, seen[alias])
	}
	return b.String()
}

// RenderConnectRegistration joins the descriptor-owned service catalog with a
// finite dependency-injection binding file and emits compile-time checked
// Connect registration. The binding file cannot contain raw Go expressions.
func RenderConnectRegistration(catalogDocument, bindingDocument []byte) ([]byte, error) {
	catalog, bindings, err := decodeRegistrationInputs(catalogDocument, bindingDocument)
	if err != nil {
		return nil, err
	}

	var source strings.Builder
	source.WriteString(`// Code generated by cmd/connect-registration from generated/service-catalog.json and connect_bindings.yaml. DO NOT EDIT.

package adapters

import (
	"net/http"

	"connectrpc.com/connect"

` + importBlock(catalog, bindings, true) + `)

// Compile-time assertions keep every configured adapter aligned with the
// descriptor-generated Connect handler interface.
var (
`)
	for _, service := range catalog.GetServices() {
		binding, _, _ := bindingFor(bindings, service)
		pkgs := generatedPackagesFor(catalog, service)
		fmt.Fprintf(&source, "\t_ %s.%sHandler = (*%s)(nil)\n", pkgs.connectAlias, service.GetName(), binding.Handler)
	}
	source.WriteString(`)

// registerCatalogConnectServices registers every catalog service on one mux.
// Exact procedure paths remain owned by protoc-gen-connect-go.
func registerCatalogConnectServices(mux *http.ServeMux, server *ConnectServer, options ...connect.HandlerOption) {
`)
	for _, service := range catalog.GetServices() {
		binding, _, _ := bindingFor(bindings, service)
		pkgs := generatedPackagesFor(catalog, service)
		fmt.Fprintf(&source, "\tmux.Handle(%s.New%sHandler(&%s{%s}, options...))\n",
			pkgs.connectAlias, service.GetName(), binding.Handler, bindingInitializer(binding.Source))
	}
	source.WriteString("}\n")

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Connect registration: %w", err)
	}
	return formatted, nil
}

// RenderGRPCRegistration derives the transitional raw-gRPC registration from
// the same complete catalog and finite implementation binding as Connect. A
// grpc source is already a generated gRPC implementation; a singleton source
// is required to return one. Business sources are Connect-native and remain on
// the catalog-complete Connect/gRPC/gRPC-Web listener until P1-NET-001 retires
// the legacy raw-gRPC listener.
func RenderGRPCRegistration(catalogDocument, bindingDocument []byte) ([]byte, error) {
	catalog, bindings, err := decodeRegistrationInputs(catalogDocument, bindingDocument)
	if err != nil {
		return nil, err
	}

	var source strings.Builder
	source.WriteString(`// Code generated by cmd/connect-registration from generated/service-catalog.json and connect_bindings.yaml. DO NOT EDIT.

package adapters

import (
	"google.golang.org/grpc"

` + importBlock(catalog, bindings, false) + `)

// registerCatalogGRPCServices registers every catalog service backed by a
// native gRPC implementation. Connect-native business handlers are served by
// the catalog-complete Connect listener and are intentionally omitted here.
func registerCatalogGRPCServices(registrar grpc.ServiceRegistrar, server *GrpcServer) {
`)
	for _, service := range catalog.GetServices() {
		binding, _, _ := bindingFor(bindings, service)
		if initializer, ok := grpcBindingInitializer(binding); ok {
			pkgs := generatedPackagesFor(catalog, service)
			fmt.Fprintf(&source, "\t%s.Register%sServer(registrar, %s)\n", pkgs.genAlias, service.GetName(), initializer)
		}
	}
	source.WriteString("}\n\n")

	source.WriteString("var catalogGRPCServiceNames = []string{\n")
	for _, service := range catalog.GetServices() {
		if binding, _, _ := bindingFor(bindings, service); !grpcBacked(binding) {
			continue
		}
		fmt.Fprintf(&source, "\t%q,\n", service.GetFullName())
	}
	source.WriteString("}\n\n")

	source.WriteString("var catalogConnectOnlyServiceNames = []string{\n")
	for _, service := range catalog.GetServices() {
		if binding, _, _ := bindingFor(bindings, service); grpcBacked(binding) {
			continue
		}
		fmt.Fprintf(&source, "\t%q,\n", service.GetFullName())
	}
	source.WriteString("}\n")

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated gRPC registration: %w", err)
	}
	return formatted, nil
}

func decodeRegistrationInputs(catalogDocument, bindingDocument []byte) (*catalogv1.ServiceCatalog, connectBindings, error) {
	catalog := &catalogv1.ServiceCatalog{}
	if err := (protojson.UnmarshalOptions{DiscardUnknown: false}).Unmarshal(catalogDocument, catalog); err != nil {
		return nil, connectBindings{}, fmt.Errorf("decode service catalog: %w", err)
	}
	if err := business.ValidateServiceCatalog(catalog); err != nil {
		return nil, connectBindings{}, fmt.Errorf("validate service catalog: %w", err)
	}

	bindings, err := decodeConnectBindings(bindingDocument)
	if err != nil {
		return nil, connectBindings{}, err
	}
	if err := validateConnectBindingCoverage(catalog, bindings); err != nil {
		return nil, connectBindings{}, err
	}
	return catalog, bindings, nil
}

func decodeConnectBindings(document []byte) (connectBindings, error) {
	var bindings connectBindings
	decoder := yaml.NewDecoder(bytes.NewReader(document))
	decoder.KnownFields(true)
	if err := decoder.Decode(&bindings); err != nil {
		return connectBindings{}, fmt.Errorf("decode Connect bindings: %w", err)
	}
	if bindings.Version != connectBindingsVersion {
		return connectBindings{}, fmt.Errorf("unsupported Connect bindings version %q", bindings.Version)
	}
	if len(bindings.Services) == 0 {
		return connectBindings{}, fmt.Errorf("no services in Connect bindings")
	}
	return bindings, nil
}

func validateConnectBindingCoverage(catalog *catalogv1.ServiceCatalog, bindings connectBindings) error {
	wanted := make(map[string]struct{}, len(catalog.GetServices()))
	for _, service := range catalog.GetServices() {
		binding, name, exists := bindingFor(bindings, service)
		wanted[name] = struct{}{}
		if !exists {
			return fmt.Errorf("missing Connect binding for catalog service %q", service.GetFullName())
		}
		if !token.IsIdentifier(binding.Handler) {
			return fmt.Errorf("invalid handler identifier %q for Connect service %q", binding.Handler, name)
		}
		switch binding.Source.Kind {
		case "business":
			if binding.Source.Name != "" {
				return fmt.Errorf("business source of Connect service %q must not declare a name", name)
			}
		case "grpc", "singleton":
			if !token.IsIdentifier(binding.Source.Name) {
				return fmt.Errorf("invalid %s source name %q for Connect service %q", binding.Source.Kind, binding.Source.Name, name)
			}
		default:
			return fmt.Errorf("unsupported source kind %q for Connect service %q", binding.Source.Kind, name)
		}
		if binding.GRPCServer != "" {
			if binding.Source.Kind != "business" {
				return fmt.Errorf("grpc_server on Connect service %q is allowed only for a business source", name)
			}
			if !token.IsIdentifier(binding.GRPCServer) {
				return fmt.Errorf("invalid grpc_server %q for Connect service %q", binding.GRPCServer, name)
			}
		}
	}

	var extras []string
	for service := range bindings.Services {
		if _, exists := wanted[service]; !exists {
			extras = append(extras, service)
		}
	}
	if len(extras) > 0 {
		sort.Strings(extras)
		return fmt.Errorf("services in Connect bindings are absent from the catalog: %s", strings.Join(extras, ", "))
	}
	return nil
}

func grpcBacked(binding connectBinding) bool {
	_, ok := grpcBindingInitializer(binding)
	return ok
}

func bindingInitializer(source connectBindingSource) string {
	switch source.Kind {
	case "business":
		return "svc: server.service"
	case "grpc":
		return "inner: server.grpc." + source.Name
	case "singleton":
		return "inner: " + source.Name + "()"
	default:
		panic("validated Connect binding source kind became invalid")
	}
}

func grpcBindingInitializer(binding connectBinding) (string, bool) {
	if binding.GRPCServer != "" {
		return "server." + binding.GRPCServer, true
	}
	switch binding.Source.Kind {
	case "grpc":
		return "server." + binding.Source.Name, true
	case "singleton":
		return binding.Source.Name + "()", true
	case "business":
		return "", false
	default:
		panic("validated Connect binding source kind became invalid")
	}
}
