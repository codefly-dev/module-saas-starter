package main

// The hop in front of every composed module, on a cell.
//
// Every module admits only a call the hop admitted: a single-use admission
// signed over the method, the module's audience, the Work Context's digest, a
// nonce and a 30-second window, verified against the admission keys the host
// publishes in Keys. A local run composes the authority module, whose edge is
// the browser's origin and whose hop signs. A cell composes no authority
// module, so this gateway is the hop there: it is built from the same library
// the authority's hop service is (codefly-dev/authority libraries/hop), and
// decides nothing the library does not.
//
// Two doors reach it:
//
//   - the hop endpoint, the hop's faces, for a composed workload calling a
//     module with a Work Context addressed to it (a module calling another, a
//     solution's runnable binding). The library asks the authority's Check
//     whether the method may run for that context, signs the admission and
//     forwards the call to the exact listener hop-routes names.
//   - a browser's module call on this gateway's own listener, after the catalog
//     found no route of this host's: the person is authenticated as on every
//     protected route, the authority's Issue gives the person's Work Context at
//     the module the path belongs to, and the call goes through the same HTTP
//     face in-process. Whether the person may use the module at all is the
//     authority's answer (Issue, then Check), never this gateway's.
//
// The signing key is generated by each instance at boot and never leaves it:
// the host pins one key per hop instance, so replicas sharing a delivered seed
// would refuse each other's registration. The instance registers the public
// half with the host under its workload credential (module-identity) and a
// proof signed by the key, and renews it while it runs.
//
// The composition names the modules in hop/MODULES; Codefly generates
// hop-routes from their published API catalogs. A run that states no
// hop/MODULES stands no hop here and registers no key: its module paths stay
// unexposed and the hop faces refuse every call by name. hop is a workspace
// group, so a local run that composes the authority module's hop delivers it
// to this gateway too; the gateway then stands beside that hop with a key of
// its own, and the authority edge still routes the local browser to the
// authority's hop.

