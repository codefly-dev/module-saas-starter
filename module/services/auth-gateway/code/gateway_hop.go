// hopIssuer is the authority interface's Issue, as its generated client serves
// it: the person's Work Context at the module a browser call is for.
type hopIssuer interface {
	Issue(ctx context.Context, in *authorityv1.IssueRequest, opts ...grpc.CallOption) (*authorityv1.IssueResponse, error)
}

// hopRole is the hop this gateway stands as on a cell.
type hopRole struct {
	// modules are the audiences hop/MODULES names, in a stable order.
	modules []string
	routes  *routing.Routing
	issuer  hopIssuer
	// face is the library's HTTP face: it decides with the authority's Check,
	// signs the admission and forwards to the published listener.
	face http.Handler
	now  func() time.Time

	mu   sync.Mutex
	held map[[32]byte]heldWorkContext
}

// heldWorkContext is a person's Work Context at one module, held until shortly
// before it lapses. The session that asked for it is re-authenticated on every
// call before it is used.
type heldWorkContext struct {
	token string
	renew time.Time
}

// newHopSigner is this instance's admission key, generated here and never
// delivered: one key per hop instance.
func newHopSigner() (*stamp.Signer, error) {
	seed := make([]byte, 32)
	if _, err := rand.Read(seed); err != nil {
		return nil, fmt.Errorf("hop: generate this instance's admission key: %w", err)
	}
	return stamp.NewSigner(hex.EncodeToString(seed))
}

// hopModules reads hop/MODULES: the modules this hop stands in front of.
func hopModules(listed string) []string {
	seen := map[string]bool{}
	var out []string
	for _, name := range strings.Split(listed, ",") {
		if name = strings.TrimSpace(name); name != "" && !seen[name] {
			seen[name] = true
			out = append(out, name)
		}
	}
	sort.Strings(out)
	return out
}

// moduleFor is the module a browser request is for: the one audience among
// hop/MODULES whose published routes resolve this request, as the hop's own
// decision will resolve it. None is not a module call; more than one is
// refused rather than guessed.
func (h *hopRole) moduleFor(r *http.Request) (string, error) {
	method := r.Method + " " + r.URL.Path
	var found []string
	for _, module := range h.modules {
		if _, _, err := h.routes.Resolve(module, "http", method); err == nil {
			found = append(found, module)
		}
	}
	switch len(found) {
	case 0:
		return "", nil
	case 1:
		return found[0], nil
	default:
		return "", fmt.Errorf("%s is published by more than one module (%s)", method, strings.Join(found, ", "))
	}
}

// serveBrowser serves a person's module call through the hop, and reports
// whether the request was one. It runs only after this host's catalog matched
// no route, so a catalog route always wins.
func (g *Gateway) serveBrowser(w http.ResponseWriter, r *http.Request) bool {
	h := g.hop
	if h == nil {
		return false
	}
	module, err := h.moduleFor(r)
	if err != nil {
		hopBrowserError(w, r, http.StatusConflict, codes.AlreadyExists, err.Error())
		return true
	}
	if module == "" {
		return false
	}
	// A module's routes under a /v1/ prefix this host's catalog owns would be
	// served in part: the catalog takes every path it matches first. Refused
	// whole rather than split between two authorities.
	if prefix, ok := v1Prefix(r.URL.Path); ok {
		if _, reserved := g.matcher.ReservedV1Prefixes()[prefix]; reserved {
			hopBrowserError(w, r, http.StatusForbidden, codes.PermissionDenied, "module "+module+" publishes a route under this host's own /v1/"+prefix+" prefix")
			return true
		}
	}
	// The person, as on every protected route: drop what a caller said about
	// who it is, then the access-token check, revocation included.
	stripAllIdentityHeaders(r)
	checked, err := g.authz.Check(r.Context(), buildCheckRequest(r))
	if err != nil {
		hopBrowserError(w, r, http.StatusInternalServerError, codes.Internal, "auth check failed")
		return true
	}
	if denied := checked.GetDeniedResponse(); denied != nil {
		code := int(denied.GetStatus().GetCode())
		if code == 0 {
			code = http.StatusForbidden
		}
		hopBrowserError(w, r, code, codes.Code(checked.GetStatus().GetCode()), denied.GetBody())
		return true
	}
	if codes.Code(checked.GetStatus().GetCode()) != codes.OK {
		hopBrowserError(w, r, http.StatusForbidden, codes.PermissionDenied, "forbidden")
		return true
	}
	injectHeaders(r, checked.GetOkResponse().GetHeaders())
	bearer, _ := strings.CutPrefix(r.Header.Get("Authorization"), "Bearer ")
	if bearer == "" {
		hopBrowserError(w, r, http.StatusUnauthorized, codes.Unauthenticated, "a module call needs a session: present an access token as `Authorization: Bearer`")
		return true
	}
	// The module's calls consume the organization's budget, as a catalog
	// route's do.
	entry := &RouteEntry{Service: hopServicePrefix + module, Protected: true}
	g.rateLimitThenServe(w, r, entry, http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		token, err := h.workContext(r.Context(), bearer, module)
		if err != nil {
			code := http.StatusForbidden
			switch status.Code(err) {
			case codes.Unauthenticated:
				code = http.StatusUnauthorized
			case codes.Unavailable, codes.DeadlineExceeded:
				code = http.StatusServiceUnavailable
			}
			hopBrowserError(w, r, code, status.Code(err), "the authority refused this person at "+module+": "+status.Convert(err).Message())
			return
		}
		h.face.ServeHTTP(w, withOnlyWorkContext(r, token))
	}))
	return true
}

// Connect owns protocol error rendering. Require an explicit protocol signal
// so REST JSON callers retain the HTTP status/body contract.
var hopErrorWriter = connect.NewErrorWriter(connect.WithRequireConnectProtocolHeader())

func hopBrowserError(w http.ResponseWriter, r *http.Request, httpCode int, code codes.Code, reason string) {
	if hopErrorWriter.IsSupported(r) {
		_ = hopErrorWriter.Write(w, r, connect.NewError(connect.Code(code), errors.New(reason)))
		return
	}
	httpError(w, httpCode, reason)
}

// hopServicePrefix marks the RouteEntry of a module call through the hop, for
// the rate limiter's key and nothing else: no upstream is resolved from it.
const hopServicePrefix = "hop:"

// withOnlyWorkContext is r as the hop's face receives it: the person's Work
// Context and nothing a caller or this gateway said about who it is. No
// Authorization, no Cookie, no identity header and no x-codefly-* header
// travels on; the face writes the admission itself.
func withOnlyWorkContext(r *http.Request, token string) *http.Request {
	out := r.Clone(r.Context())
	stripAllIdentityHeaders(out)
	out.Header.Del("Authorization")
	out.Header.Del("Cookie")
	out.Header.Del("Proxy-Authorization")
	for name := range out.Header {
		if strings.HasPrefix(strings.ToLower(name), "x-codefly-") {
			out.Header.Del(name)
		}
	}
	out.Header.Set(hop.WorkContextKey, token)
	return out
}

// workContext is the person's Work Context at module, issued by the authority
// for what the person holds there and held until shortly before it lapses.
// The hop's Check narrows each call to what its method requires.
func (h *hopRole) workContext(ctx context.Context, bearer, module string) (string, error) {
	key := sha256.Sum256([]byte(bearer + "\x00" + module))
	now := h.clock()
	h.mu.Lock()
	for k, held := range h.held {
		if !now.Before(held.renew) {
			delete(h.held, k)
		}
	}
	if held, ok := h.held[key]; ok {
		h.mu.Unlock()
		return held.token, nil
	}
	h.mu.Unlock()
	ask, cancel := context.WithTimeout(metadata.AppendToOutgoingContext(ctx, "authorization", "Bearer "+bearer), 10*time.Second)
	defer cancel()
	issued, err := h.issuer.Issue(ask, &authorityv1.IssueRequest{
		As:       &authorityv1.IssueRequest_Person{Person: &authorityv1.PersonSession{}},
		Audience: module,
	})
	if err != nil {
		return "", err
	}
	if issued.GetToken() == "" {
		return "", status.Error(codes.Internal, "the authority issued no Work Context")
	}
	expires := time.Unix(issued.GetExpiresAtUnix(), 0)
	lead := min(expires.Sub(now)/2, 30*time.Second)
	held := heldWorkContext{token: issued.GetToken(), renew: expires.Add(-lead)}
	h.mu.Lock()
	if h.held == nil {
		h.held = map[[32]byte]heldWorkContext{}
	}
	if now.Before(held.renew) {
		h.held[key] = held
	}
	h.mu.Unlock()
	return held.token, nil
}

func (h *hopRole) clock() time.Time {
	if h.now != nil {
		return h.now()
	}
	return time.Now()
}

// standHop stands this gateway as the hop when the composition names modules
// for it (hop/MODULES), through the hop library's front door: the faces the
// hop endpoint serves, and the browser path's in-process
// face. accounts is the authority interface's connection (its Connect
// listener, which serves the interface over gRPC too). No hop/MODULES is no
// hop: nil, and nothing registered. A composition that names modules but whose
// hop cannot stand is refused, by name, at boot.
func standHop(ctx context.Context, accounts grpc.ClientConnInterface) (*hopRole, *forward.Front, error) {
	listed, _, err := codefly.For(ctx).WorkspaceValueIfSet("hop", "MODULES")
	if err != nil {
		return nil, nil, fmt.Errorf("hop/MODULES cannot be read: %w", err)
	}
	modules := hopModules(listed)
	if len(modules) == 0 {
		return nil, nil, nil
	}
	raw, err := codefly.For(ctx).WorkspaceConfiguration("hop-routes", "ROUTES")
	if err != nil {
		return nil, nil, forward.MissingRoutes(err)
	}
	routes, err := routing.DecodeRouting(raw)
	if err != nil {
		return nil, nil, forward.MissingRoutes(err)
	}
	enforcement, _, err := codefly.For(ctx).WorkspaceValueIfSet("hop", "ENFORCEMENT")
	if err != nil {
		return nil, nil, fmt.Errorf("hop/ENFORCEMENT cannot be read: %w", err)
	}
	// This instance registers its key as the workload the run attests
	// (module-identity: true).
	return newHopRole(ctx, hopAuthority{authorityv1.NewAuthorityServiceClient(accounts)}, hop.RunCredential, modules, raw, routes, enforcement)
}

// hopAuthorityClient is what the hop asks of the authority interface: Check
// and RegisterAdmissionKey for the front door, Issue for a browser's call.
type hopAuthorityClient interface {
	forward.Authority
	hopIssuer
}

// hopAuthority is the interface's generated client, as hopAuthorityClient.
type hopAuthority struct {
	authorityv1.AuthorityServiceClient
}

// newHopRole builds the front door and the browser path over it, with a key
// this instance generates.
func newHopRole(ctx context.Context, authority hopAuthorityClient, credential func() (string, error),
	modules []string, raw string, routes *routing.Routing, enforcement string,
) (*hopRole, *forward.Front, error) {
	signer, err := newHopSigner()
	if err != nil {
		return nil, nil, err
	}
	front, err := forward.New(ctx, forward.Config{
		Signer: signer, Authority: authority, Credential: credential,
		Modules: modules, Routes: raw, Enforcement: enforcement, Log: wool.Get(ctx).In("hop"),
	})
	if err != nil {
		return nil, nil, err
	}
	log.Printf("hop: standing in front of %s", strings.Join(modules, ", "))
	return &hopRole{modules: modules, routes: routes, issuer: authority, face: front.Handler}, front, nil
}

// hopFace is the hop's one face, as the hop endpoint serves it: a gRPC call
// (HTTP/2, application/grpc) goes to the front door's gRPC face, which carries
// it to the module as opaque frames; every other request — Connect and HTTP
// routes — to its HTTP face. One endpoint, because an exported gRPC endpoint
// must publish a contract of its own, and the hop serves none: it forwards
// the contracts its modules publish. accounts serves its internal gRPC tier on
// its REST port the same way.
func hopFace(grpcFace *grpc.Server, httpFace http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.ProtoMajor == 2 && strings.HasPrefix(r.Header.Get("Content-Type"), "application/grpc") {
			grpcFace.ServeHTTP(w, r)
			return
		}
		httpFace.ServeHTTP(w, r)
	})
}

// serveHop listens on the hop endpoint, as the run allocated it, with the
// front door's faces over HTTP/1.1 and HTTP/2 without TLS (the mesh carries
// in-cell transport); with no hop, every call is answered with the reason. It
// returns what stops it.
func serveHop(ctx context.Context, front *forward.Front) (func(), error) {
	at, err := codefly.For(ctx).Endpoint("hop").API("http").ResolveNetworkInstance()
	if err != nil || at == nil || at.Port == 0 {
		return nil, fmt.Errorf("hop: the hop endpoint does not resolve: %v", err)
	}
	options := []grpc.ServerOption{grpc.UnknownServiceHandler(noHopStream)}
	var httpFace http.Handler = http.HandlerFunc(noHopHTTP)
	if front != nil {
		options, httpFace = front.ServerOptions, front.Handler
	}
	grpcFace := grpc.NewServer(options...)
	listener, err := net.Listen("tcp", fmt.Sprintf(":%d", at.Port))
	if err != nil {
		return nil, fmt.Errorf("hop: listen on the hop endpoint: %w", err)
	}
	protocols := new(http.Protocols)
	protocols.SetHTTP1(true)
	protocols.SetUnencryptedHTTP2(true)
	// No WriteTimeout: a forwarded streaming call holds its response open, as
	// on the gateway's own listener.
	server := &http.Server{Handler: hopFace(grpcFace, httpFace), Protocols: protocols,
		ReadHeaderTimeout: 10 * time.Second, IdleTimeout: 120 * time.Second, MaxHeaderBytes: 1 << 20}
	go func() { _ = server.Serve(listener) }()
	log.Printf("hop listening on :%d", at.Port)
	return func() {
		drain, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		_ = server.Shutdown(drain)
		grpcFace.Stop()
	}, nil
}

// errNoHop is every call to the hop endpoint of a gateway that stands no hop.
var errNoHop = status.Error(codes.Unavailable, "this gateway stands no hop: the composition names no module in hop/MODULES")

func noHopStream(any, grpc.ServerStream) error { return errNoHop }

func noHopHTTP(w http.ResponseWriter, _ *http.Request) {
	httpError(w, http.StatusServiceUnavailable, status.Convert(errNoHop).Message())
}
